"""Text normalization: the layer that decides *what counts as the same text*.

Two texts are kept side by side at all times:

* ``original_text``  — exactly what the extractor produced (evidence).
* ``normalized_text``— the comparable form (NFKC, whitespace collapsed,
  dates/currency/numbers canonicalised, optionally case-folded).

Both are hashed and stored, so a reviewer can always audit what the pipeline
compared.

Why normalization is a *service* and not a library call
-----------------------------------------------------
Every rule below is a deliberate, documented decision that changes verification
outcomes, and each one trades a little recall for a lot of precision:

``dd/mm/yyyy`` vs ``mm-dd-yyyy``
    Dates written with ``/`` are read day-first and dates written with ``-``
    month-first (a common South-Asian/US mix). ISO ``yyyy-mm-dd`` is recognised
    by its 4-digit leading year and never rewritten. Ambiguous input is
    normalised *deterministically*, never guessed at random — the date order
    table in :data:`DATE_ORDER_BY_SEPARATOR` is the single source of truth.

Currency
    ``₹1,50,000.00``, ``Rs 150000`` and ``INR 150000.00`` all normalise to
    ``INR 150000.00``, so a document generated by a different vendor template
    still matches its twin. Currency *identity* is preserved (``$`` becomes
    ``USD``) so that 1000 USD never matches 1000 INR.

Case folding and identifiers
    **Identifiers are never case-folded.** Template patterns such as
    ``\\b[A-Z]{2}\\d{4}\\b`` (``INV1234``) require uppercase input, and a
    case-folded digest would make ``INV1234`` and ``inv1234`` collide even
    though the *pattern that validated them* rejected the lowercase form. Any
    token containing both an uppercase letter and a digit is therefore written
    to the normalized text in its original case. This is a conservative choice:
    it may report two documents as *different* when they differ only in the case
    of an identifier, which is exactly the right direction for a verification
    system (a false "identical" is far more damaging than a false "different").
"""

from __future__ import annotations

import re
import time
import unicodedata
from dataclasses import dataclass, field
from typing import Any, Dict, Iterable, List, Optional, Sequence

from app.algorithms.hashing import sha256_text
