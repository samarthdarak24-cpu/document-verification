# --------------------------------------------------------------------------- #
# Tokenisation (shared with the algorithm core)
# --------------------------------------------------------------------------- #
#: Lowercase alphanumeric tokens — deliberately the *same* rule used by
#: ``app.algorithms.lcs.tokenize`` so a normalized document fed to LCS/edit
#: distance is tokenised identically by both layers.
_COMPARISON_TOKEN_RE = re.compile(r"[^\W_]+", re.UNICODE)

#: A token that carries both an uppercase letter and a digit is an identifier.
_IDENTIFIER_RE = re.compile(r"^(?=[A-Za-z0-9._/-]*[A-Z])(?=[A-Za-z0-9._/-]*\d)[A-Za-z0-9._/-]{2,}$")


def normalize_for_comparison(text: str) -> List[str]:
    """Return the lowercase alphanumeric tokens of ``text``.

    This is the token sequence consumed by LCS, edit distance and the
    3-gram shingle fingerprints. It intentionally drops punctuation and case,
    which is what makes "Invoice #AB1234" and "invoice ab1234" comparable —
    the *identifier case rule* above applies to the normalized *text*, not to
    the comparison tokens (the comparison is a similarity signal, not an
    equality claim; equality claims are made by the two hashes).
    """
    if not text:
        return []
    return _COMPARISON_TOKEN_RE.findall(text.lower())


def normalized_text_hash(text: str) -> str:
    """Return the SHA-256 of the already-normalized ``text``."""
    return sha256_text(text)


# --------------------------------------------------------------------------- #
# Unicode + whitespace
# --------------------------------------------------------------------------- #
#: Characters that survive NFKC but still break naive comparisons.
_FANCY_QUOTES = {
    "\u2018": "'", "\u2019": "'", "\u201a": "'", "\u201b": "'",
    "\u201c": '"', "\u201d": '"', "\u201e": '"',
    "\u2013": "-", "\u2014": "-", "\u2015": "-",
    "\u00a0": " ", "\u202f": " ", "\u2007": " ", "\u2028": " ",
    "\ufb01": "fi", "\ufb02": "fl",  # NFKC handles these, kept for clarity
}


def unicode_normalize(text: str) -> str:
    """Apply NFKC plus a compatibility table for dashes/quotes/nbsp."""
    if not text:
        return ""
    text = unicodedata.normalize("NFKC", text)
    for source, target in _FANCY_QUOTES.items():
        text = text.replace(source, target)
    return text


def collapse_whitespace(text: str) -> str:
    """Collapse every whitespace run to one space and strip the ends.

    Line structure is *not* preserved here (the extractor's newlines carry
    document structure, which the structure service needs); call
    :func:`normalize_text` with ``keep_line_breaks=True`` to retain it.
    """
    if not text:
        return ""
    return re.sub(r"[ \t\r\f\v]+", " ", text).strip()


def collapse_all_whitespace(text: str) -> str:
    """Collapse whitespace *including* newlines (used for hashing)."""
    if not text:
        return ""
    return re.sub(r"\s+", " ", text).strip()


# --------------------------------------------------------------------------- #
# Dates
# --------------------------------------------------------------------------- #
MONTHS: Dict[str, int] = {
    "january": 1, "jan": 1,
    "february": 2, "feb": 2,
    "march": 3, "mar": 3,
    "april": 4, "apr": 4,
    "may": 5,
    "june": 6, "jun": 6,
    "july": 7, "jul": 7,
    "august": 8, "aug": 8,
    "september": 9, "sep": 9, "sept": 9,
    "october": 10, "oct": 10,
    "november": 11, "nov": 11,
    "december": 12, "dec": 12,
}

#: Which component comes first for each numeric separator (see module docstring).
DATE_ORDER_BY_SEPARATOR = {
    "/": "day_first",   # 25/12/2024 -> 2024-12-25
    "-": "month_first", # 12-25-2024 -> 2024-12-25
}

_ISO_DATE_RE = re.compile(r"\b(?P<y>19|20)\d{2}-(?P<m>0[1-9]|1[0-2])-(?P<d>0[1-9]|[12]\d|3[01])\b")
_NUMERIC_DATE_RE = re.compile(
    r"(?<![\d/])(?P<a>0?[1-9]|[12]\d|3[01])(?P<sep>[/\-.])(?P<b>0?[1-9]|1[0-2])(?P=sep)(?P<y>(?:19|20)\d{2})(?![\d/])"
)
_DMY_TEXT_RE = re.compile(
    r"\b(?P<d>0?[1-9]|[12]\d|3[01])(?:st|nd|rd|th)?\s+(?P<month>January|February|March|April|May|June|July|August|September|October|November|December|Jan|Feb|Mar|Apr|Jun|Jul|Aug|Sep|Sept|Oct|Nov|Dec)\s+(?P<y>(?:19|20)\d{2})\b",
    re.IGNORECASE,
)
_MDY_TEXT_RE = re.compile(
    r"\b(?P<month>January|February|March|April|May|June|July|August|September|October|November|December|Jan|Feb|Mar|Apr|Jun|Jul|Aug|Sep|Sept|Oct|Nov|Dec)\.?\s+(?P<d>0?[1-9]|[12]\d|3[01])(?:st|nd|rd|th)?,?\s+(?P<y>(?:19|20)\d{2})\b",
    re.IGNORECASE,
)


def _iso(year: str, month: str, day: str) -> str:
    return f"{int(year):04d}-{int(month):02d}-{int(day):02d}"


def _valid_iso(year: int, month: int, day: int) -> bool:
    if not (1 <= month <= 12):
        return False
    days_in_month = [31, 29 if (year % 4 == 0 and (year % 100 != 0 or year % 400 == 0)) else 28,
                     31, 30, 31, 30, 31, 31, 30, 31, 30, 31]
    return 1 <= day <= days_in_month[month - 1]


def normalize_dates(text: str) -> str:
    """Rewrite every recognised date as ISO ``yyyy-mm-dd``.

    Handled forms: ``12 March 2024``, ``March 12, 2024``, ``12/03/2024``
    (day first), ``03-12-2024`` (month first) and ISO passthrough. The separator
    is the day/month disambiguator — see :data:`DATE_ORDER_BY_SEPARATOR`.

    A numeric date whose day/month cannot be resolved into a real calendar date
    in *either* order is left untouched (better an unmodified string than a
    confidently wrong date). When exactly one interpretation is valid (e.g.
    ``25/12/2024``) that one is used.
    """
    if not text:
        return ""

    def _numeric(match: re.Match) -> str:
        a, sep, b, year = match.group("a"), match.group("sep"), match.group("b"), match.group("y")
        order = DATE_ORDER_BY_SEPARATOR.get(sep, "day_first")
        first, second = (a, b) if order == "day_first" else (b, a)
        year_i = int(year)
        try:
            if _valid_iso(year_i, int(second), int(first)):
                return _iso(year, second, first)
            if _valid_iso(year_i, int(first), int(second)):
                # Only the opposite reading is a real date: use it and keep the
                # decision visible by emitting ISO (unambiguous by definition).
                return _iso(year, first, second)
        except ValueError:
            return match.group(0)
        return match.group(0)

    text = _NUMERIC_DATE_RE.sub(_numeric, text)

    def _dmy(match: re.Match) -> str:
        month = MONTHS.get(match.group("month").lower())
        if not month:
            return match.group(0)
        return _iso(match.group("y"), str(month), match.group("d"))

    def _mdy(match: re.Match) -> str:
        month = MONTHS.get(match.group("month").lower())
        if not month:
            return match.group(0)
        return _iso(match.group("y"), str(month), match.group("d"))

    text = _DMY_TEXT_RE.sub(_dmy, text)
    text = _MDY_TEXT_RE.sub(_mdy, text)
    return text


def parse_date(value: str) -> Optional[str]:
    """Parse a single date value to ISO, or return ``None`` if unrecognised."""
    if not value:
        return None
    candidate = collapse_whitespace(value)
    if _ISO_DATE_RE.fullmatch(candidate):
        return candidate
    normalized = normalize_dates(candidate)
    match = _ISO_DATE_RE.search(normalized)
    if match:
        return match.group(0)
    return None


# --------------------------------------------------------------------------- #
# Currency & numbers
# --------------------------------------------------------------------------- #
CURRENCY_TOKENS = {
    "₹": "INR", "rs": "INR", "rs.": "INR", "inr": "INR", "₹.": "INR",
    "$": "USD", "usd": "USD", "us$": "USD",
    "€": "EUR", "eur": "EUR",
    "£": "GBP", "gbp": "GBP",
    "aed": "AED", "sar": "SAR", "aud": "AUD", "cad": "CAD",
}

_CURRENCY_NUMBER_RE = re.compile(
    r"(?P<symbol>₹\s*|Rs\.?\s*|INR\s*|\$\s*|USD\s*|US\$\s*|€\s*|EUR\s*|£\s*|GBP\s*)"
    r"(?P<amount>\d{1,3}(?:,\d{2,3})*(?:\.\d{1,2})?|\d+(?:\.\d{1,2})?)",
    re.IGNORECASE,
)
_CODE_CURRENCY_RE = re.compile(
    r"\b(?P<code>INR|USD|EUR|GBP|AED|SAR|AUD|CAD)\s*(?P<amount>\d[\d,]*(?:\.\d{1,2})?)",
    re.IGNORECASE,
)
_GROUPED_NUMBER_RE = re.compile(r"(?<=\d),(?=\d{3}(\D|$))")


def _clean_amount(raw: str) -> str:
    """Strip grouping commas and normalise the decimal part."""
    amount = raw.replace(",", "").replace(" ", "")
    if amount.startswith("."):
        amount = "0" + amount
    if amount.endswith("."):
        amount = amount[:-1]
    return amount


def normalize_currency(text: str) -> str:
    """Canonicalise money expressions to ``<CODE> <amount>``.

    ``₹1,50,000.00`` -> ``INR 150000.00``; ``$1,000`` -> ``USD 1000``. Currency
    identity is preserved so cross-currency comparisons do not collide.
    """
    if not text:
        return ""

    def _symbol(match: re.Match) -> str:
        symbol = match.group("symbol")
        code = None
        for token, candidate in CURRENCY_TOKENS.items():
            if symbol.lower().startswith(token.lower()):
                code = candidate
                break
        if code is None:
            code = "INR"
        return f"{code} {_clean_amount(match.group('amount'))}"

    text = _CURRENCY_NUMBER_RE.sub(_symbol, text)

    def _code(match: re.Match) -> str:
        code = match.group("code").upper()
        return f"{code} {_clean_amount(match.group('amount'))}"

    text = _CODE_CURRENCY_RE.sub(_code, text)
    return text


def normalize_numbers(text: str) -> str:
    """Remove thousands separators from digit runs (``12,500`` -> ``12500``)."""
    if not text:
        return ""
    return _GROUPED_NUMBER_RE.sub("", text)


def normalize_label(label: str) -> str:
    """Normalize a *field label* for matching: lowercase, punctuation trimmed.

    Used to line up template labels with document labels
    (``"Invoice  No.:"`` -> ``"invoice no"``).
    """
    if not label:
        return ""
    collapsed = unicodedata.normalize("NFKC", label).lower()
    collapsed = re.sub(r"[^a-z0-9]+", " ", collapsed)
    return collapsed.strip()


# --------------------------------------------------------------------------- #
# Case folding with identifier protection
# --------------------------------------------------------------------------- #
def is_identifier_token(token: str) -> bool:
    """True when ``token`` looks like a case-sensitive identifier.

    "Contains an uppercase letter *and* a digit" (``INV1234``, ``AB1234``,
    ``A-1-2024``). Purely alphabetic acronyms (``GST``) are not identifiers by
    this rule because no template pattern depends on their case.
    """
    return bool(_IDENTIFIER_RE.match(token))


def case_fold(text: str, fold: bool = True) -> str:
    """Lowercase ``text`` while preserving identifier tokens' case.

    When ``fold`` is False the text is returned unchanged.
    """
    if not fold or not text:
        return text
    tokens = text.split(" ")
    out: List[str] = []
    for token in tokens:
        if token and is_identifier_token(token):
            out.append(token)  # never case-fold identifiers (see module docstring)
        else:
            out.append(token.lower())
    return " ".join(out)


# --------------------------------------------------------------------------- #
# Top-level normalization
# --------------------------------------------------------------------------- #
@dataclass
class NormalizedDocument:
    """Original and normalized text, their tokens and their hashes."""

    original_text: str
    normalized_text: str
    comparison_tokens: List[str] = field(default_factory=list)
    original_hash: str = ""
    normalized_hash: str = ""
    char_count: int = 0
    token_count: int = 0
    steps: Dict[str, float] = field(default_factory=dict)
    notes: List[str] = field(default_factory=list)

    @property
    def has_text(self) -> bool:
        return bool(self.normalized_text.strip())

    def to_dict(self) -> Dict[str, Any]:
        return {
            "char_count": self.char_count,
            "token_count": self.token_count,
            "original_hash": self.original_hash,
            "normalized_hash": self.normalized_hash,
            "comparison_tokens_sample": self.comparison_tokens[:25],
            "steps": {key: round(value, 3) for key, value in self.steps.items()},
            "notes": list(self.notes),
        }


def normalize_text(
    text: str,
    *,
    case_fold_enabled: bool = True,
    keep_line_breaks: bool = False,
) -> NormalizedDocument:
    """Run the full normalization pipeline and return a :class:`NormalizedDocument`.

    ``keep_line_breaks=False`` (the default used for comparison) collapses
    newlines too, which makes the normalized text a single canonical line and is
    what the normalized-text hash is computed over. Structure detection uses the
    *original* text precisely because it needs the line boundaries.
    """
    started = time.perf_counter()
    original = text or ""
    notes: List[str] = []

    timings: Dict[str, float] = {}

    mark = time.perf_counter()
    working = unicode_normalize(original)
    timings["unicode"] = (time.perf_counter() - mark) * 1000

    mark = time.perf_counter()
    working = normalize_dates(working)
    timings["dates"] = (time.perf_counter() - mark) * 1000

    mark = time.perf_counter()
    working = normalize_currency(working)
    timings["currency"] = (time.perf_counter() - mark) * 1000

    mark = time.perf_counter()
    working = normalize_numbers(working)
    timings["numbers"] = (time.perf_counter() - mark) * 1000

    mark = time.perf_counter()
    if keep_line_breaks:
        # Collapse intra-line runs only; newlines are structural.
        working = "\n".join(
            collapse_whitespace(line) for line in working.splitlines()
        ).strip()
    else:
        working = collapse_all_whitespace(working)
    timings["whitespace"] = (time.perf_counter() - mark) * 1000

    mark = time.perf_counter()
    working = case_fold(working, fold=case_fold_enabled)
    timings["case_fold"] = (time.perf_counter() - mark) * 1000

    if case_fold_enabled:
        protected = [tok for tok in working.split() if is_identifier_token(tok)]
        if protected:
            notes.append(
                f"{len(protected)} identifier-like token(s) kept their original "
                f"case (identifier case is significant for template patterns)."
            )

    mark = time.perf_counter()
    tokens = normalize_for_comparison(working)
    timings["tokenize"] = (time.perf_counter() - mark) * 1000

    result = NormalizedDocument(
        original_text=original,
        normalized_text=working,
        comparison_tokens=tokens,
        original_hash=sha256_text(original),
        normalized_hash=normalized_text_hash(working),
        char_count=len(working),
        token_count=len(tokens),
        steps=timings,
        notes=notes,
    )
    result.steps["total"] = (time.perf_counter() - started) * 1000
    return result


def excerpt(text: str, limit: int = 2000) -> str:
    """Return at most ``limit`` characters of ``text`` for the preview column."""
    if not text:
        return ""
    if len(text) <= limit:
        return text
    return text[: limit - 3].rstrip() + "..."


def normalize_many(values: Iterable[str]) -> List[str]:
    """Normalize a list of label-ish strings with :func:`normalize_label`."""
    return [normalize_label(value) for value in values]


def raise_if_not_text(text: str) -> None:
    """Guard used by callers that require real content (defensive)."""
    if not text or not text.strip():
        raise ServiceError("No text content to normalize.", "empty_text")


def sequence_stats(sequence: Sequence[str]) -> Dict[str, Any]:
    """Small helper for the analytics router."""
    return {
        "count": len(sequence),
        "distinct": len(set(sequence)),
        "total_length": sum(len(item) for item in sequence),
    }
