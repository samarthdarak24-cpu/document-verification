def seed_settings(db: Session) -> Dict[str, Any]:
    """Insert missing default settings; return the resulting settings map."""
    created = 0
    for key, value in DEFAULT_SETTINGS:
        existing = db.execute(
            select(ApplicationSetting).where(ApplicationSetting.key == key)
        ).scalar_one_or_none()
        if existing is None:
            db.add(ApplicationSetting(key=key, value_json=value))
            created += 1
    if created:
        db.commit()
    return load_settings(db)


def load_settings(db: Session) -> Dict[str, Any]:
    """Return every setting, filling gaps from :data:`DEFAULT_SETTINGS`."""
    values: Dict[str, Any] = {key: value for key, value in DEFAULT_SETTINGS}
    rows = db.execute(select(ApplicationSetting)).scalars().all()
    for row in rows:
        values[row.key] = row.value_json
    return values


def seed_templates(db: Session) -> List[DocumentTemplate]:
    """Insert the default templates (and their fields) when absent."""
    created: List[DocumentTemplate] = []
    for spec in DEFAULT_TEMPLATES:
        existing = db.execute(
            select(DocumentTemplate).where(DocumentTemplate.name == spec["name"])
        ).scalar_one_or_none()
        if existing is not None:
            continue
        template = DocumentTemplate(
            name=spec["name"],
            category=spec["category"],
            description=spec["description"],
            required_fields=list(spec["required_fields"]),
            optional_fields=list(spec["optional_fields"]),
            critical_fields=list(spec["critical_fields"]),
            expected_sections=list(spec["expected_sections"]),
            section_order=list(spec["section_order"]),
            aliases=dict(spec["aliases"]),
        )
        for name, data_type, required, pattern, critical, position in spec["fields"]:
            template.fields.append(
                TemplateField(
                    name=name,
                    data_type=data_type,
                    required=required,
                    validation_pattern=pattern,
                    critical=critical,
                    position=position,
                )
            )
        db.add(template)
        created.append(template)
    if created:
        db.commit()
    return created


def seed_defaults(db: Session) -> Dict[str, Any]:
    """Seed settings and templates; returns ``{"settings": n, "templates": n}``."""
    settings = seed_settings(db)
    templates = seed_templates(db)
    return {"settings": len(settings), "templates": len(templates)}


